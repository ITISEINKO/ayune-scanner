const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const ts = require("typescript");

const source = readFileSync("src/features/panel-viewer/panelViewer.ts", "utf8");
const update = source.slice(source.indexOf("\tconst update = () => {"), source.indexOf("\tconst scaleLabels ="));
assert.ok(update.includes("renderer.render(scene, camera)"));
const code = ts.transpileModule(`${update}\nreturn update;`, { compilerOptions: { target: ts.ScriptTarget.ES2020 } }).outputText;
const base = {}, hardware = {}, outline = {};
const settings = { xray: false, hideDoors: false, numbers: false, explode: 0 };
const materials = new Map([["wood", base]]);
const run = new Function("settings", "materials", "hingeMaterial", "outlineMaterial", "renderer", "panels", "scene", "camera", "hasSelection", "doorProgress", code);
const render = { domElement: { dataset: {} }, render() {} };
const check = (hasSelection) => run(settings, materials, hardware, outline, render, [], {}, {}, hasSelection, 0)();
check(true);
assert.equal(base.opacity, 0.1);
assert.equal(hardware.opacity, 0.1);
assert.equal(outline.opacity, 0.15);
check(false);
assert.equal(base.opacity, 1);
assert.equal(hardware.opacity, 1);
assert.equal(outline.opacity, 0.55);
settings.xray = true;
check(false);
assert.equal(base.opacity, 0.28);
assert.equal(outline.opacity, 0.55);
check(true);
assert.equal(outline.opacity, 0.55);
const selectionSource = source.slice(source.indexOf("\t\tsetSelected(id?: string, pinnedId?: string) {"), source.indexOf("\t\tsetDoorsOpen(open: boolean)"));
const selectionCode = ts.transpileModule(`return ({${selectionSource}}).setSelected;`, { compilerOptions: { target: ts.ScriptTarget.ES2020 } }).outputText;
const original = { color: "wood", map: "texture", clone() { return { ...this }; } };
const panel = { part: { id: "p" }, baseMaterial: original, selectedOutline: {}, mesh: {} };
const selectedMaterials = new Map();
const select = new Function("panels", "selectedMaterials", "selectedOutlineMaterial", "inspectedOutlineMaterial", "update", "hasSelection", selectionCode)([panel], selectedMaterials, {}, {}, () => {}, false);
select("p");
assert.equal(panel.mesh.material.color, "wood");
assert.equal(panel.mesh.material.map, "texture");
assert.equal(panel.mesh.material.opacity, 1);
assert.equal(panel.mesh.material.depthWrite, true);
select();
assert.equal(panel.mesh.material, original);
console.log("Viewer selection and X-ray opacity checks passed");
