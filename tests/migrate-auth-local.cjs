const assert = require("node:assert/strict");
const { mkdtempSync, writeFileSync, existsSync, readdirSync } = require("node:fs");
const { join } = require("node:path");
const { tmpdir } = require("node:os");
const { spawnSync } = require("node:child_process");
const { createClient } = require("@libsql/client");
const { migrate } = require("../scripts/migrate-auth-local.cjs");

(async () => {
	const dir = mkdtempSync(join(tmpdir(), "auth-migrate-"));
	const path = join(dir, "old.db"), membersPath = join(dir, "members.json");
	const db = createClient({ url: `file:${path.replaceAll("\\", "/")}` });
	await db.execute("CREATE TABLE ppic_permissions (clickup_user_id TEXT PRIMARY KEY, display_name TEXT, role TEXT, allowed_status TEXT, active INTEGER, can_import_lby INTEGER, updated_by TEXT, updated_at TEXT)");
	await db.execute("INSERT INTO ppic_permissions VALUES ('123', 'Admin', 'ADMIN', 'BARANG_DITERIMA', 1, 0, 'actor', '2026-01-01'), ('456', 'Inactive', 'MEMBER', 'BARANG_DITERIMA', 0, 0, 'actor', '2026-01-01')");
	const members = [{ id: "123", email: "admin@example.test", name: "Admin" }];
	await assert.rejects(migrate(db, []), /active user needs a real email/);
	assert.equal((await db.execute("SELECT count(*) n FROM ppic_permissions")).rows[0].n, 2);
	assert.equal((await db.execute("SELECT count(*) n FROM sqlite_master WHERE name='user'")).rows[0].n, 0);
	const preview = await migrate(db, members);
	assert.equal(preview.created, 2);
	assert.equal(preview.placeholders, 1);
	assert.equal((await db.execute("SELECT count(*) n FROM sqlite_master WHERE name='user'")).rows[0].n, 0, "preview rolls back schema and data");
	writeFileSync(membersPath, JSON.stringify(members));
	const result = spawnSync(process.execPath, ["scripts/migrate-auth-local.cjs", "--database", path, "--members", membersPath, "--apply"], { cwd: process.cwd(), encoding: "utf8" });
	assert.equal(result.status, 0, result.stderr);
	const applied = JSON.parse(result.stdout);
	assert.equal(applied.applied, true);
	assert(existsSync(applied.backup));
	const backup = createClient({ url: `file:${applied.backup.replaceAll("\\", "/")}` });
	assert.equal((await backup.execute("SELECT count(*) n FROM ppic_permissions")).rows[0].n, 2);
	backup.close();
	assert.equal(readdirSync(dir).filter((name) => name.includes("before-auth-migration")).length, 1);
	assert.equal((await db.execute("SELECT count(*) n FROM user")).rows[0].n, 2);
	assert.equal((await db.execute("SELECT count(*) n FROM account")).rows[0].n, 2);
	assert.equal((await db.execute("SELECT count(*) n FROM sqlite_master WHERE name='ppic_permissions'")).rows[0].n, 0);
	assert.equal((await db.execute("SELECT permission_updated_by FROM user WHERE role='ADMIN'")).rows[0].permission_updated_by, "actor");
	assert.equal((await db.execute("PRAGMA integrity_check")).rows[0].integrity_check, "ok");
	assert.equal((await migrate(db, members)).alreadyMigrated, true);
	const rerun = spawnSync(process.execPath, ["scripts/migrate-auth-local.cjs", "--database", path, "--members", membersPath, "--apply"], { cwd: process.cwd(), encoding: "utf8" });
	assert.equal(rerun.status, 0, rerun.stderr);
	assert.equal(JSON.parse(rerun.stdout).alreadyMigrated, true);
	assert.equal(readdirSync(dir).filter((name) => name.includes("before-auth-migration")).length, 1);
	db.close();
	const invalid = createClient({ url: ":memory:" });
	await invalid.execute("CREATE TABLE user (id TEXT)");
	await assert.rejects(migrate(invalid, []), /Missing user.name/);
	invalid.close();
	const conflict = createClient({ url: ":memory:" });
	await conflict.execute("CREATE TABLE ppic_permissions (clickup_user_id TEXT, display_name TEXT, role TEXT, allowed_status TEXT, active INTEGER, can_import_lby INTEGER, updated_by TEXT, updated_at TEXT)");
	await conflict.execute("INSERT INTO ppic_permissions VALUES ('1', 'One', 'MEMBER', 'BARANG_DITERIMA', 1, 0, 'actor', 'now'), ('2', 'Two', 'MEMBER', 'BARANG_DITERIMA', 1, 0, 'actor', 'now')");
	await assert.rejects(migrate(conflict, [{ id: '1', email: 'same@example.test' }, { id: '2', email: 'same@example.test' }], true), /UNIQUE/);
	assert.equal((await conflict.execute("SELECT count(*) n FROM ppic_permissions")).rows[0].n, 2);
	assert.equal((await conflict.execute("SELECT count(*) n FROM sqlite_master WHERE name='user'")).rows[0].n, 0);
	conflict.close();
})().catch((error) => { console.error(error); process.exitCode = 1; });
